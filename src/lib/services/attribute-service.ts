export async function getCategoryAttributes(categoryIdOrSlug: string): Promise<CategoryAttribute[]> {
  const matching = DEFAULT_CATEGORY_ATTRIBUTES.filter((a) => {
    if (a.category_id === categoryIdOrSlug) return true;
    // Map standard slugs
    if (categoryIdOrSlug === 'is-makineleri' && a.category_id === 'a0000000-0000-0000-0000-000000000001') return true;
    if (categoryIdOrSlug === 'yapi-malzemeleri' && a.category_id === 'a0000000-0000-0000-0000-000000000002') return true;
    if (categoryIdOrSlug === 'nakliye' && a.category_id === 'a0000000-0000-0000-0000-000000000003') return true;
    if (categoryIdOrSlug === 'iskele-kalip' && a.category_id === 'cat-iskele-kalip') return true;
    if (categoryIdOrSlug === 'asansor-platform' && a.category_id === 'cat-asansor-platform') return true;
    if (categoryIdOrSlug === 'santiye-ekipmanlari' && a.category_id === 'cat-santiye-ekipmanlari') return true;
    if (categoryIdOrSlug === 'insaat-hizmetleri' && a.category_id === 'cat-insaat-hizmetleri') return true;
    return false;
  });

  return matching.sort((a, b) => a.order_index - b.order_index);
}

export async function addCategoryAttribute(attr: Omit<CategoryAttribute, 'id'>): Promise<CategoryAttribute> {
  const newAttr: CategoryAttribute = {
    ...attr,
    id: `attr-${Date.now()}`,
    created_at: new Date().toISOString(),
  };
  DEFAULT_CATEGORY_ATTRIBUTES.push(newAttr);
  return newAttr;
}

